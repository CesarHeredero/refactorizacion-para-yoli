                <h2>Palmeras en la Nieve</h2>

                <hr>
                <p><span class="glyphicon glyphicon-time"></span> Enero 13, 2016</p>

                <hr>
                <img class="img-responsive" src="images/palmeras-en-la-nieve.jpg" alt="Película: Palmeras en la Nieve" title="Película: Palmeras en la Nieve" >
                <hr>
                <p class="lead"><span class="glyphicon glyphicon-play"></span> <a href="https://www.youtube.com/embed/bpLfd9Q7SwA?rel=0&autoplay=1" target="_blank">VER TRAILER</a></p>
                <hr>
                
                <p><strong>Basada en el libro de Luz Gabás.</strong></p>
                
                <p><strong>Sinopsis</strong>: Killian dejará su Pasolobino (Orense) querido, para viajar a Guinea Ecuatorial a trabajar en la recogida del cacao junto con su hermano Jacobo y su padre. La finca Samkalpa le espera, allí le asignarán un boy llamado Simón, que le ayudará a conocer mejor, los dos ambientes que vive, por un lado los nativos y por otro los colonos. El padre de Killian le querrá enseñar la pureza de la tierra donde viven, para ello le hará conocer rincones desconocidos junto con amistades que traspasan cualquier barrera, los oriundos son nativos de la tierra que nada tienen que ver con los que trabajan en la finca. allí conocerá la amistad, el odio pero sobre todo el amor, un amor prohibido con una nativa llamada Bisila, casada con un Oriundo. El amor prohibido le harán traspasar hasta las fronteras del año 2003, que Clarence viajará a Guinea para averiguar la verdad de su tío Killian y su padre Jacobo. Una carta será el punto de partida para averiguar toda la verdad de sus antepasados.</p>
                
                <p><strong>Género</strong>: Drama</p>
                
                <p><strong>Año</strong>: 2015</p>
                
                <p><strong>Duración</strong>: 163 minutos</p>
                
                <hr>
                
                <p><strong>Critica y valoración</strong>: El viaje que viví en el momento de empezar la lectura del libro, es más que comparable como el director ha sabido plasmar en esta superproducción, todo la magia de Luz Gabás.  Es una obra tan delicada, tan exquisita, es un viaje del que no quieres que te bajen nunca, un barco sin timón solo lo que te guía la magnífica película. Música penetrante que acompaña a unos paisajes que te hacen vivir la historia como si el protagonista fueras tú. Fotografía que te teletransportan a un mundo paralelo, donde dejas volar la imaginación de sus delicados escenarios. Conexión entre los protagonistas, se hace evidente, que en ella pusieron un punto de inicio de una relación duradera. Berta Vázquez un descubrimiento, es muy especial ella como su personaje, deja evidente que va a tener una carrera muy prometedora, Mario Casas de siempre me ha gustado, no solo por lo que es evidente sino por su crecimiento en la gran pantalla, aquí sale más a la luz, lo que va consiguiendo con los años. Dos cosas que hace que no se convierta en un cinco, como es la duración de la película dos horas y media, que para mi parecer es innecesario alargar la historia, y poner la música de banda sonora al final de la película, si he vivido en primera persona un desazón de sentimientos con esta gran composición de Pablo Alborán hubiese sido el colofón final a esta gran historia.</p>
                
