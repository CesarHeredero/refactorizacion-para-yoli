                <p><strong>Critica y valoración</strong>: Una   película húngara que repasa la historia más vergonzosa inhumana del   siglo XX. Para mí un film dedicado a la fe humana, aunque viendo lo   acontecido ¿dónde estaba el ser divino, para salvar a esta gente   inocente?, muestras aparte, siendo católica mi religión, os puedo decir   que sigue el sentido de la vida y la muerte, aunque en el mensaje   subliminal, no halles la razón de porque anteponer la vida a la muerte.   Armas que le valen, tanto por lo valiente de la imposición, como la   manera desahogada de contarlo, una infinidad de elogios , en abundante   ascenso. Un film del siglo XXI, que nos recuerda en cuerda humana el   infierno vivido y la fe por mantenerse en pie.</p>
                
