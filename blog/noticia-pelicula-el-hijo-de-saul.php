                <p><strong>Sinopsis</strong>: Año   1944, Auschwitz Campo de concentración. Saúl judío húngaro es   prisionero y encargado de retirar los cadáveres gaseados en las cámaras   de los prisioneros judíos. Pero un día encuentra entre todos los   cadáveres un superviviente, un niño, que poco tarda en morir, Saúl le   hará pasar como su hijo, y buscará cualquier forma humana, de poder   darle sepultura como se merece.</p>
                
                <p><strong>Género</strong>: Drama</p>
                
                <p><strong>Año</strong>: 2015</p>
                
