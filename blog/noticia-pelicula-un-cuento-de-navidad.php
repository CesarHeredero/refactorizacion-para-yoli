                <p><strong>Sinopsis</strong>: Belle trabaja con su padre en el sector de compraventa de propiedades y   antigüedades. Muy próxima a las Navidades les encargan una tasación   entera de una gran mansión, el propietario le corre mucha prisa ponerla a   la venta, por ello Belle se tendrá que trasladar cuanto antes a la gran   mansión. Cuando llega al lugar y ve la maravilla que tiene que tasar,   se alegra de poder pasar unos días en una casa tan estupenda, aunque   cuando conozca al dueño, no le gustará tanto ya que es una persona   malhumorada, borde y despreciable. Pero Belle hará todo lo posible por   hacer su trabajo, mientras que entre ellos surgirá algo. Un cuento de   Navidad para estas fechas.</p>
                
                <p><strong>Género</strong>: Drama</p>
                
                <p><strong>Año</strong>: 2013</p>
                
                <p><strong>Duración</strong>: 90 minutos</p>
                
                <hr>
                
                <p><strong>Critica y valoración</strong>: En estas fechas me preparo una ristra de   películas Navideñas, para que enciendan como es debido mi Navidad. De   todas las que he podido ver estos días, he elegido esta, ya que dicta   mucho que desear todas las películas que se ruedan con ambiente   navideño. Es una película sin complejos, como la protagonista que diré   al respecto que me encanta que haya una actriz rellenita, actuando en un   film, ya que todas parecen tocadas con la varita mágica del hada de   Cenicienta. Destacar nada más, ya que es una película de tercer o cuarto   rango, pero eso sí te despierta en estas fechas las ilusiones, el   espíritu navideño y como no, esa sonrisa de: ¡Que historia más bonita¡!.   “A mí no me pasan esas cosas". Para sentimentales y con espíritu   navideño, abstenerse gente contraria a estas fechas.</p>
                
