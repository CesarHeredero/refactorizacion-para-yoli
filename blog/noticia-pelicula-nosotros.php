                <p><strong>Sinopsis</strong>: La familia Wilson se dispone  un año más a pasar sus vacaciones veraniegas en la casita que tienen en la playa. Adelaide (Lupita Nyong´o) en la misma playa donde van a pasar el día con unos amigos, fue donde estuvo 15 minutos desaparecida de pequeña, además de enfrentarse a sus miedos pasados al volver ahí, tendrá un nuevo frente abierto y es, que, cuando vuelven a casa después del día de playa, se encontrarán fuera de su  casa, a cuatro personas dos adultos y dos niños dándose las manos y queriendo querer entrar en su casa. Qué pasará con la familia Wilson?.</p>
                
