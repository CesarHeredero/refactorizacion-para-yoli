                <p><strong>Critica y valoración</strong>: Esta película es un insulto a la inteligencia del espectador, nunca me ha pasado de salir literalmente cabreada del cine, porque me he sentido engañada con esta película, pero lo peor de todo no es eso, es sentarme a leer las críticas y ver que todo es positivo de esta gran bazofia cinematográfica. Lo primero que este género Terror, Jordan Peele lo ha reinventado pero a su manera, cuando me siento a ver una película de terror, es terror, no una mezcla de pongo todo lo que se me pasa por la cabeza y hago un cocktail de humor negro, risa y algún sustito de puertas abiertas. Destacar un género para mi es la clave de una buena película, La película empieza bien hasta? que los majetes estos llegan a casa después de un día de playa. ahí empieza un recorrido de mal gusto, un mírame ¡y dime¡ si estás viendo lo mismo que ¡yo¡. Lo mejor del film Lupita Nyong´o lo peor ? todo lo demás. No hago la crítica más profunda porque no quiero hacer spoiler de esta gran mentira. Ahora bien, he aprendido que el género de Terror es como sentarte a jugar a la ruleta rusa, y tengo que valorar antes de ir por un impulso directivo.</p>
                
