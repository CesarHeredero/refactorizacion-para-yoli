                <p><strong>Sinopsis</strong>: Rachel (Emily Blunt) coge el mismo tren todos los días, a la misma hora, para ir a trabajar a Nueva York. En el trayecto le gusta mirar siempre la misma casa y la pareja que vive en ella, imaginando sus vidas perfectas, hecho que hace evadirse de su drama personal. Su marido la ha dejado yéndose a vivir con otra mujer, con la que ha tenido una niña. Rachel se ahoga de todos sus problemas con el alcohol, ingiriendo grandes cantidades todos los días. Hoy cogerá el mismo tren de todos los días, pero observará que algo extraño está pasando en la casa de los Hipwell, Megan está besándose con otro hombre, y ese mismo día desaparece sin dejar rastro. Todo esto hará que Rachel busque respuestas pero sobre todo averiguar que le ha pasado a la dulce Megan (Haley Bennett).</p>
                
