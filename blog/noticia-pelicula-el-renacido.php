                <p><strong>Sinopsis</strong>: 1823, Hugh Glass (Leonardo DiCaprio) pertenece a una expedición que viaja a la America profunda, se dedican a poner trampas para cazar animales y vender sus pieles. Los nativos del lugar les siguen muy de cerca para arrebatarles las pieles conseguidas, eso provocará una guerra sin cuartel que les hará huir a las profundidades del bosque. Hugh será atacado por un oso, además un compañero matará a su único hijo, y encima le dejará tirado a su suerte en el bosque, pero él renacerá para volver y vengar la muerte de su hijo.</p>
                
