                <p><strong>Sinopsis</strong>: A    sus 12 años Connor (Lewis MacDougall), vive entre su mundo de fantasía   donde se aísla de su cruda realidad, una madre enferma de cáncer y un   padre ausente, solo tiene a su abuela, una mujer ruda con mucho   temperamento, que le impone doctrinas que para su edad, son difíciles de   asimilar. Un monstruo (Liam Neeson) vendrá a verle, para ayudarle con   sus fobias miedos pero sobre todo para asimilar lo que se le viene   encima. </p>
                
                <p><strong>Género</strong>: Fantasía</p>
                
                <p><strong>Año</strong>: 2016</p>
                
                <p><strong>Duración</strong>: 108 minutos</p>
                
                <hr>
                
                <p><strong>Critica y valoración</strong>: Directa   y concisa, la peor película de Bayona. argumento sin sentido, que ralla   la exasperación de no entender ningún concepto del film. No puedo negar   que, tiene unos efectos especiales alucinantes, Lewis Macdougall   Connor, esta impresionante encarnando el papel principal, todo muy bien,   hasta que llega el monstruo, contando historias para no dormir, sin   sentido enredando este amasijo de incoherencias. Creo que se a   idealizado este film, antes del estreno, ya te preguntas como será, ese   es el verdadero arte de vender aire, aun precio de cine. </p>
                
