                <p><strong>Sinopsis</strong>: James Donovan (Tom Hanks) un abogado de Brooklyn le asignan un caso de Rudolf Abel (Marc Rylance) al   que le acusan de ser espía Soviético, James tendrá que luchar por   defender a alguien que ya le han condenado antes del juicio. Al mismo   tiempo de que suceda todo esto, un piloto estadounidense será capturado   por la URSS, y ahora querrán el cambio entre Rudolf Abel   (Soviético), Austin Stowell (Estadounidense), este trabajo se lo   encargarán también a James Donovan, el será el encargado de viajar a   Berlín para entregar a Rudolf y traerse a Austin.</p>
                
                <p><strong>Género</strong>: Drama Thriller</p>
                
                <p><strong>Año</strong>: 2015</p>
                
                <p><strong>Duración</strong>: 130 minutos</p>
                
                <hr>
                
                <p><strong>Critica y valoración</strong>: Esta película tiene luces y sombras, siempre desde mi humilde opinión,   cuando se trata de Spielberg me pongo mis mejores galas, solo él sabe   hacer y dirigir cualquier género que le pongas delante. Pues delante   tenemos una trama de espionaje de trama perfecto, de escenarios   perfectos, atrezzo, un largo etc, se puede contar, cuando se trata de   él, pero hay algo que para es muy importante a la hora de que me atrape   una película, y es el comienzo, con esta película me ha pasado que ha   sido tan lineal, al principio que no he llegado a meterme en la historia   hasta pasada más de media hora. Tom Hanks su actor fetiche está   perfecto, pero destaco mucho más como actor secundario a Mark Rylance,   además que con esta película opta a bastantes premios, un actor con   muchos trabajos, pero siempre desde la sombra. También me ha   decepcionado mucho la música siempre elegida con minucioso mimo por   Spielberg, no ha llegado a conectar tampoco con el film. Luces todas,   pero sombras bastantes, para enturbiar mi nota. No obstante creo que   nadie tiene que perderse esta película, animo a todo el mundo que la vea   y tome sus propias conclusiones.</p>
                
