                <hr>
                
                <p><strong>Critica y valoración</strong>: Abrir   la novela de Rudyard por la página uno, y escoger la mejor adaptación   hasta ahora hecha. Un concepto familiar, que une a niños y adultos. Los   paisajes te envuelven como la temible Ka, las garras te atrapan como un   despertar. Lo mejor ver a sus personajes en libertad, en su habitad   natural, disfrutando con sus leyes y dejando al temible hombre que tanto   hace daño a la especie. Mowgli lleva el peso de la película, ayudado   eso si por sus personajes animados, pero es admirable la entereza y   sostén que tiene un niño tan joven. Abre el primer capítulo y no pares   hasta el final, te espera una gran aventura.</p>
                
