                <p><strong>Nueva adaptación de la novela de Rudyard Kipling.</strong></p>
                
                <p><strong>Sinopsis</strong>: Mowgli (Neel Sethi) apodado en la selva como el cachorro humano esta creciendo en la selva desde que Magila la pantera negra se lo encontró cuando era pequeño y decidió, entregarlo a la manada de lobos, para que lo criaran igual que a sus lobeznos. Pero Mowgli ya no esta seguro el temible Sercan quiere terminar con su vida, como antaño acabó con la vida del padre de Mowgli. Ahora tendrá que emprender el camino hacia los que son de su especie y pueden ponerle a salvo de las garras de Sercan.</p>
                
