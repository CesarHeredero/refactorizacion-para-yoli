                <h2>Loving Pablo</h2>

                <hr>
                <p><span class="glyphicon glyphicon-time"></span> Julio 23, 2018</p>

                <hr>
                <img class="img-responsive" src="images/pablo.jpg" alt="Película: Loving Pablo" title="Película: Loving Pablo" >
                <hr>
                <p class="lead"><span class="glyphicon glyphicon-play"></span> <a href="https://www.youtube.com/embed/ydPC_TeCz6U?rel=0&autoplay=1" target="_blank">VER TRAILER</a></p>
                <hr>
                
                <p><strong>Sinopsis</strong>: <strong>Basada en el libro “Amando a Pablo, Odiando a Escobar” basada  además en la historia real del narcotraficante más famoso de todos los tiempos.</strong> En la década de los 80 Pablo Escobar Gaviria (Javier Bardem) era el gran jefe en Colombia, todo la droga que se consumía y se introducía en Estados unidos, estaba dirigida por Pablo. En este film basado en el libro escrito por la periodista Virginia Vallejo (Penélope Cruz), cuenta la historia de amor que vivió junto al narcotraficante más famoso del mundo. </p>
                
                <p><strong>Género</strong>: Biográfico</p>
                
                <p><strong>Año</strong>: 2017</p>
                
                <p><strong>Duración</strong>: 123 minutos</p>
                
                <hr>
                
                <p><strong>Crítica y valoración</strong>: Un film que lo tenía todo para ser un éxito arrollador,  en taquilla, El director Fernando León de Aranoa y la oscarizada pareja Pe Bardem. Bien es cierto que a esta pareja de actores se les quiere más fuera que dentro, nunca han sabido ganarse al público de casa, Fue una película que se retiró a las tres semanas de vida en las pantallas de cine. Aquí da comienzo mi crítica de esta Hiper versionada historia.</p>
                
                <p>Otra mirada y en este caso de la periodista que estuvo más de cinco años de relación con Pablo. Aquí se conocen aspectos nuevos que todavía no habían contado en  series o películas varias. La recreación de los escenarios esta impecable, viajando a los años 80 a través de sus ropas y complementos . Aquí el gran jefe Pablo o mejor dicho Bardem, hace uno de los papeles de su vida, solo por verle nuevamente actuar y meterse en el papel del narcotraficante, estaría dispuesta a verla otra vez. Penélope Cruz le sigue bien los pasos, pero descansando en el camino a repostar, le queda mucho camino para una interpretación tan magnífica que nos ha regalado su marido y la manera que tiene de acercarse al mal con tanto acierto. Nuestro malo malísimo Bardem.</p>

				<p>Nota curiosa: Javier Bardem estuvo viviendo en Colombia un año, para perfeccionar su acento colombiano. No le doy más nota por la dureza de escenas, añadiendo imágenes perfectamente imaginables. además de entrever que el presupuesto se lo han llevado ellos, no contratando a otros geniales actores para que den el salto al soñado charco.</p>
                
