                <p><strong>Basado en el relato de Stephen King, Todo Oscuro, Sin Estrellas.</strong></p>
                
                <p><strong>Sinopsis</strong>: Darcy (Joan Allen) y Bob Anderson (Anthony Lapaglia) es un matrimonio que celebran sus  Veinticinco Aniversario con una gran fiesta. En la vida de los Anderson todo parece perfecto, hasta que una noche Darcy descubre que su amado esposo, es un peligroso asesino en serie, que ha matado a mas de 12 mujeres, como será su vida a partir de descubrir al asesino Bidy?</p>
                
