                <p><strong>Critica y valoración</strong>: De   puertas para adentro de una casa, hasta las cenefas despuntan y son   afiladas. Cuando elegí la película impulsada por supuesto por el maestro   Stephen King, me imaginaba que iba ser la típica película como la   antecesora " Lo que la Verdad Esconde", pero mi sorpresa es mayúscula,   cuando encuentro una intriga insospechada, donde todo parece nuevo e   inesperado, bueno tratándose de King, no hay conjeturas al respecto.   Joan Allen es ideal para dar vida a la esposa perfecta, Aunque he decir   que estos finales heroico que tanto peca el que dirige sus películas,   hablando de Peter Askin son unas cuantas, que atropella el final y   desmantela una trama que podría ser tan caótica como la escritura del   maestro King.</p>
                
